-- Vighna-Darshi shared alert and incident tables.
-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  severity text not null default 'warning'
    check (severity in ('info', 'warning', 'high', 'critical')),
  created_by text not null default 'admin',
  created_at timestamptz not null default now(),
  active boolean not null default true
);

create table if not exists public.incidents (
  id bigint generated by default as identity primary key,
  incident_type text not null,
  description text not null,
  vehicle_id text not null default 'KA01AB1234',
  reported_by text not null default 'partner',
  status text not null default 'open',
  created_at timestamptz not null default now()
);

create index if not exists alerts_created_at_idx
  on public.alerts (created_at desc);
create index if not exists incidents_created_at_idx
  on public.incidents (created_at desc);

-- The Python backend uses a server-side secret/service-role key and is responsible
-- for access. Never put that key in frontend JavaScript or commit it to source control.
alter table public.alerts enable row level security;
alter table public.incidents enable row level security;
